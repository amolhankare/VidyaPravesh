import { BlockInfo } from '../types';

function mkBlock(name: string, customClusters?: string[]): BlockInfo {
  const clusters = customClusters && customClusters.length > 0
    ? customClusters
    : [`${name.split(' ')[0]} केंद्र १ (Center 1)`, `${name.split(' ')[0]} केंद्र २ (Center 2)`, `${name.split(' ')[0]} केंद्र ३ (Center 3)`];

  return {
    name,
    clusters: clusters.map((cName, idx) => ({
      name: cName,
      totalSchools: 30 + ((idx * 7) % 20),
    })),
  };
}

